/**
 * Generate `src/data/datasets/<id>/primalist-form-variants.ts` from
 * `exported_powers/<id>/primalist_misc/{primal,hunter,prowler}_form_powers/*.json`.
 *
 * Thunderspy's Primalist is a Kheldian-style form-shifter: its six Feral Might
 * attacks (Feral_Blow, Vicious_Strike, Brutal_Swipe, Primal_Strike, Upheaval,
 * Savage_Blow) plus Primal_Gift's Primal_Howl are EMPTY redirect shells in the
 * pickable powersets — the real per-form effect data lives in these
 * Primalist_Misc form-power sets. Which variant fires is decided by the active
 * form (Primal = human/default, Hunter, Prowler).
 *
 * Emits BOTH the per-variant Power data (PRIMALIST_FORM_VARIANT_POWERS, keyed by
 * internalName, same overlay shape the InfoPanel form-redirect reads) and the
 * base→{primal,hunter,prowler} redirect map (PRIMALIST_REDIRECTS), derived from
 * the `_Primal`/`_Hunter`/`_Prowler` variant suffixes.
 *
 * Usage: node scripts/generate-primalist-variants.cjs --dataset thunderspy
 */

const fs = require('fs');
const path = require('path');
const { parseDatasetArg, datasetPath } = require('./_dataset-paths.cjs');
const { extractEffects, extractDamage, normalizeIconPath, collectAllTemplates, EFFECT_AREA_MAP, applyThunderspyDamageType } = require('./convert-powerset.cjs');

const datasetId = parseDatasetArg();
const RAW_DATA_BASE = path.join(__dirname, '../exported_powers');
const RAW_DATA_PATH = (datasetId === 'homecoming' && !fs.existsSync(path.join(RAW_DATA_BASE, datasetId)))
  ? RAW_DATA_BASE
  : path.join(RAW_DATA_BASE, datasetId);
const MISC_PATH = path.join(RAW_DATA_PATH, 'primalist_misc');

// folder → form key
const FORM_FOLDERS = {
  primal_form_powers: 'primal',
  hunter_form_powers: 'hunter',
  prowler_form_powers: 'prowler',
};

const OUTPUT_PATH = datasetPath(datasetId, 'primalist-form-variants.ts');

function load() {
  const variants = {};
  const redirects = {}; // base internalName -> { primal, hunter, prowler }
  if (!fs.existsSync(MISC_PATH)) {
    console.warn(`No primalist_misc data at ${MISC_PATH}; emitting empty maps.`);
    return { variants, redirects };
  }
  for (const [folder, form] of Object.entries(FORM_FOLDERS)) {
    const dir = path.join(MISC_PATH, folder);
    if (!fs.existsSync(dir)) continue;
    for (const file of fs.readdirSync(dir)) {
      if (!file.endsWith('.json') || file === 'index.json') continue;
      const raw = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
      const internalName = raw.name;
      if (!internalName) continue;

      const stats = {};
      if (raw.accuracy != null) stats.accuracy = raw.accuracy;
      if (raw.range != null && raw.range > 0) stats.range = raw.range;
      if (raw.recharge_time != null && raw.recharge_time > 0) stats.recharge = raw.recharge_time;
      if (raw.endurance_cost != null) stats.endurance = raw.endurance_cost;
      if (raw.activation_time != null && raw.activation_time > 0) stats.castTime = raw.activation_time;
      if (raw.activate_period != null && raw.activate_period > 0) stats.activatePeriod = raw.activate_period;
      if (raw.radius != null && raw.radius > 0) stats.radius = raw.radius;
      if (raw.arc != null && raw.arc > 0) stats.arc = raw.arc;
      if (raw.max_targets_hit != null && raw.max_targets_hit > 0) stats.maxTargets = raw.max_targets_hit;

      const templates = collectAllTemplates(raw.effects || []);
      const damage = applyThunderspyDamageType(extractDamage(templates), raw.display_short_help);
      const effects = extractEffects(templates);

      variants[internalName] = {
        name: raw.display_name && !raw.display_name.startsWith('P') ? raw.display_name
            : internalName.replace(/_/g, ' '),
        internalName,
        powerType: raw.type || 'Click',
        targetType: raw.target_type || 'Foe',
        effectArea: EFFECT_AREA_MAP[raw.effect_area] ?? raw.effect_area ?? 'SingleTarget',
        shortHelp: raw.display_short_help || '',
        description: raw.display_help || '',
        icon: normalizeIconPath(raw.icon || ''),
        stats,
        ...(damage ? { damage } : {}),
        ...(effects && Object.keys(effects).length > 0 ? { effects } : {}),
      };

      // Derive base name by stripping the form suffix (case-insensitive).
      const base = internalName.replace(/_(Primal|Hunter|Prowler)$/i, '');
      if (base !== internalName) {
        (redirects[base] ??= { primal: null, hunter: null, prowler: null })[form] = internalName;
      }
    }
  }
  return { variants, redirects };
}

function emit({ variants, redirects }) {
  const header = `/**
 * Primalist form-variant power lookup + redirect map (${datasetId}).
 *
 * AUTO-GENERATED by \`scripts/generate-primalist-variants.cjs\`. Do not
 * hand-edit. Re-run when the bin export changes.
 *
 * Source: \`exported_powers/${datasetId}/primalist_misc/{primal,hunter,prowler}_form_powers/*.json\`.
 *
 * PRIMALIST_FORM_VARIANT_POWERS: per-form variant data, keyed by internalName,
 *   overlaid onto the empty base-attack shell at display time (InfoPanel).
 * PRIMALIST_REDIRECTS: base attack internalName -> per-form variant internalName
 *   (null = fall back to the Primal/default variant).
 */

import type { Power } from '@/types';

export interface PrimalistRedirectTargets {
  primal: string | null;
  hunter: string | null;
  prowler: string | null;
}

export const PRIMALIST_FORM_VARIANT_POWERS: Record<string, Partial<Power>> = ${JSON.stringify(variants, null, 2)};

export const PRIMALIST_REDIRECTS: Record<string, PrimalistRedirectTargets> = ${JSON.stringify(redirects, null, 2)};
`;
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, header);
  console.log(`Wrote ${Object.keys(variants).length} variants / ${Object.keys(redirects).length} redirects to ${OUTPUT_PATH}`);
}

emit(load());
